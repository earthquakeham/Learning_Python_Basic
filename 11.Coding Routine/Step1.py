# Step1. Think about 'input' and 'output'

# [어떤 input이 필요할까?]
# 구구단 프로그램에서 우리가 컴퓨터에게 어떤 값을 input 해야지 우리가 원하는 결과를 얻을 수 있을까? 우리는 컴퓨터에게 몇 단 구구단을 원하는지 알려줘야 한다. 즉, 2,3,4,5,6…등을 input해야 한다.
# input = 2

# [어떤 output이 필요할까?]
# 구구단 프로그램에서 우리가 컴퓨터로부터 얻기 원하는 최종적인 결과는 무엇인가? 우리는 input에 맞게 다음과 같은 결과를 얻기를 원한다.
# output = 4, 6, 8, 10, 12, 14, 16, 18

# Input, output 을 확정하면 방향이 비교적 명확해 지는 느낌을 받을 수 있다. 방향이 좁혀진다.
